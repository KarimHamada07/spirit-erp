def page_help(request):
    """(عنوان، شرح) للصفحة الحالية أو None"""
    match = getattr(request, "resolver_match", None)
    if match is None:
        return None
    name = match.url_name or ""
    if name in PAGE_HELP:
        return PAGE_HELP[name]
    # صفحات لوحة الإدارة: app_model_changelist / add / change
    for kind in ("changelist", "add", "change"):
        suffix = "_" + kind
        if name.endswith(suffix):
            key = name[: -len(suffix)].replace("_", ".", 1)
            info = MODEL_HELP.get(key)
            if info:
                text = info[0] if kind == "changelist" else info[1]
                return ("", f"{text} {ADMIN_ACTIONS[kind]}")
    return None


def help_box_html(request):
    info = page_help(request)
    if not info:
        return ""
    title, text = info
    key = escape(getattr(request.resolver_match, "url_name", "") or "")
    return (f'<div class="erp-help" data-key="{key}" role="note">'
            f'<button type="button" class="erp-help-toggle" aria-expanded="true" '
            f'data-tip="اخفي/اظهر شرح الصفحة"><i class="fas fa-circle-info" aria-hidden="true"></i> '
            f'الصفحة دي بتعمل إيه؟</button>'
            f'<div class="erp-help-body"><div>{escape(text)}</div></div></div>')


